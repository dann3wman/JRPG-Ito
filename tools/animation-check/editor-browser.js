#!/usr/bin/env node
const assert = require('assert/strict');
const fs = require('fs');
const path = require('path');
const { pathToFileURL } = require('url');
const { chromium } = require('playwright');
const { ROOT } = require('../lib/load-game');
const out = path.join(ROOT, 'output/playwright/rig-editor');
fs.mkdirSync(out, { recursive: true });

(async () => {
  const browser = await chromium.launch({ executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE || undefined, args: ['--allow-file-access-from-files'] });
  const errors = [], results = {};
  try {
    const page = await browser.newPage({ viewport: { width: 1320, height: 1000 }, acceptDownloads: true });
    page.on('pageerror', error => errors.push(error.message));
    await page.addInitScript(() => { requestAnimationFrame = () => 0; });
    await page.goto(pathToFileURL(path.join(ROOT, 'tools/bestiary-rig-viewer/index.html')).href + '?boss=orlen');
    await page.waitForFunction(() => IMG.orlen, null, { polling: 100 });
    await page.locator('#editor summary').first().click();
    await page.locator('#editMode').selectOption('setup');
    await page.locator('#tree button[data-id="forearmL"]').click();
    const original = await page.evaluate(() => {
      const rig = RIGS.orlen, M = solve(rig, makePose(rig), {}, false);
      return { pivot: [...rig.byId.forearmL.pv], hand: [...M.handL], patch: exportPatch() };
    });
    await page.locator('#pvX').fill(String(original.pivot[0] + 2));
    await page.locator('#applyBone').click();
    assert.match(await page.locator('#editStatus').textContent(), /Bone updated/);
    results.pivotPreservation = await page.evaluate(hand => {
      const rig = RIGS.orlen, M = solve(rig, makePose(rig), {}, false);
      return M.handL.every((n, i) => Math.abs(n - hand[i]) < 1e-8);
    }, original.hand);
    assert.ok(results.pivotPreservation);
    await page.locator('#undoEdit').click();
    assert.equal(await page.locator('#pvX').inputValue(), String(original.pivot[0]));
    await page.locator('#redoEdit').click();
    assert.equal(await page.locator('#pvX').inputValue(), String(original.pivot[0] + 2));
    await page.locator('#restS').fill('0');
    await page.locator('#applyBone').click();
    assert.match(await page.locator('#editStatus').textContent(), /invalid s/);
    await page.evaluate(syncEditor);
    await page.locator('#addTarget').click();
    assert.equal(await page.locator('#constraintList option').count(), 1);
    assert.match(await page.locator('#constraintList').inputValue(), /Target/);
    await page.locator('#targetX').fill('150');
    await page.locator('#targetMix').fill('0.5');
    await page.locator('#applyTarget').click();
    assert.equal(await page.evaluate(() => RIGS.orlen.constraints[0].mix), .5);
    await page.locator('#targetBend').selectOption('-1');
    await page.locator('#applyTarget').click();
    await page.locator('#editTool').selectOption('target');
    await page.locator('#stage').scrollIntoViewIfNeeded();
    await page.evaluate(render);
    const target = await page.evaluate(() => {
      const p = ap(getView(RIGS.orlen), ...RIGS.orlen.constraints[0].target), box = cv.getBoundingClientRect();
      return { x: p[0] + box.left, y: p[1] + box.top, value: [...RIGS.orlen.constraints[0].target] };
    });
    await page.mouse.move(target.x, target.y); await page.mouse.down();
    await page.mouse.move(target.x + 18, target.y + 8, { steps: 3 }); await page.mouse.up();
    assert.notDeepEqual(await page.evaluate(() => RIGS.orlen.constraints[0].target), target.value);
    results.targetDrag = true;
    await page.locator('#removeTarget').click();
    assert.equal(await page.locator('#constraintList').inputValue(), '');
    await page.locator('#editTool').selectOption('pivot');
    await page.locator('#stage').scrollIntoViewIfNeeded(); await page.evaluate(render);
    const joint = await page.evaluate(() => { const j = joints.find(j => j.id === 'forearmL'), box = cv.getBoundingClientRect(); return { x: j.x + box.left, y: j.y + box.top }; });
    await page.mouse.move(joint.x, joint.y); await page.mouse.down();
    await page.mouse.move(joint.x + 4, joint.y + 3, { steps: 3 }); await page.mouse.up();
    assert.match(await page.locator('#editStatus').textContent(), /Setup edit/);
    results.pivotDrag = true;
    const downloadPromise = page.waitForEvent('download');
    await page.locator('#exportRig').click();
    const download = await downloadPromise, patchPath = path.join(out, download.suggestedFilename());
    await download.saveAs(patchPath);
    const patch = JSON.parse(fs.readFileSync(patchPath, 'utf8'));
    assert.ok(patch.bones.length > 0); assert.equal(patch.creature, 'orlen');
    await page.reload(); await page.waitForFunction(() => IMG.orlen, null, { polling: 100 });
    await page.locator('#editor summary').first().click();
    await page.locator('#patchFile').setInputFiles(patchPath);
    await page.waitForFunction(() => document.getElementById('editStatus').textContent.includes('Patch imported'));
    assert.deepEqual(await page.evaluate(() => exportPatch()), patch);
    results.exportImport = true;
    await page.locator('#clips button').filter({ hasText: 'Crozier strike' }).click();
    await page.locator('#clipIn').fill('0');
    await page.locator('#clipMix').fill('0.3');
    await page.locator('#clipFX').fill('0.4');
    await page.locator('#markAnticipation').fill('0.1');
    await page.locator('#markImpact').fill('0.95');
    await page.locator('#markRecovery').fill('1.6');
    await page.locator('#clipHold').check();
    await page.locator('#editor details summary').click();
    await page.locator('#clipTracks').fill('[{"bone":"head","field":"r","mode":"hold","keys":[[0,0],[0.8,12]]}]');
    await page.locator('#applyClip').click();
    assert.match(await page.locator('#editStatus').textContent(), /Clip settings updated/);
    await page.locator('#markers button').filter({ hasText: 'impact' }).click();
    assert.equal(await page.evaluate(() => st.t), .95);
    await page.evaluate(() => { st.playing = true; advanceTime(5000); });
    assert.equal(await page.evaluate(() => st.anim), 'crozier');
    assert.equal(await page.evaluate(() => st.t), 2.6);
    assert.equal(await page.evaluate(() => st.playing), false);
    results.clipControls = true;
    await page.locator('#clipTracks').fill('[{"bone":"wrong","field":"r","keys":[[0,0]]}]');
    await page.locator('#applyClip').click();
    assert.match(await page.locator('#editStatus').textContent(), /invalid pose track/);
    await page.evaluate(syncEditor);
    await page.locator('#tBounds').check(); await page.locator('#tFitFX').check();
    await page.evaluate(render);
    await page.screenshot({ path: path.join(out, 'desktop.png'), fullPage: true });
    for (const width of [390, 320]) {
      await page.setViewportSize({ width, height: 844 });
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'editor must fit ' + width);
      await page.screenshot({ path: path.join(out, 'mobile-' + width + '.png'), fullPage: true });
    }
    await page.setViewportSize({ width: 1320, height: 900 });
    results.interruptionPixels = await page.evaluate(async () => {
      setBoss('widow'); await load('widow'); setArena('none'); st.playing = false; st.mode = 'animation';
      $('tBounds').checked = false; $('tBones').checked = false; $('tRef').checked = false; $('editor').open = false;
      st.anim = 'undertow'; st.t = 1.2; st.clock = 2.57; st.blend = null; st.hitAt = -1;
      render(); const before = cv.toDataURL();
      playClip('lullaby'); st.playing = false; render(); return before === cv.toDataURL();
    });
    assert.ok(results.interruptionPixels, 'interrupting an action preserves rendered outgoing FX at blend start');
    await page.locator('#stage').screenshot({ path: path.join(out, 'interruption.png') });
    assert.deepEqual(errors, []);
    results.errors = errors;
    fs.writeFileSync(path.join(out, 'report.json'), JSON.stringify(results, null, 2) + '\n');
    console.log(JSON.stringify(results, null, 2));
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
